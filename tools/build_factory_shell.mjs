#!/usr/bin/env node
/*
 * build_factory_shell.mjs — building.config.json → factory_precision.obj + building_meta.json
 *
 *   Generates the empty factory building the /v2 viewer loads: floor slab, steel frames
 *   (wall columns, rafters, interior post lines, end-wall columns), purlins, girts, outer walls
 *   with a door opening, wainscot liner, roof, ceiling light fixtures and yellow floor lines.
 *   Millimetres, Z-up, X = length, Y = width. Part names follow the conventions the viewer
 *   already keys on (Floor_Slab, Col_*, Roof_*, Girt_*, Wall_*, LinerPanel_*, HighBay_LED_*,
 *   SafetyLine_*, Joint_*), so materials, selection, shadows and lighting keep working.
 *
 *   The animated sectional gate is not re-modelled: its parts (Door_Sectional_*) are copied
 *   unchanged from the original 24 x 16 m model (legacy/factory_precision_24x16.obj). The viewer
 *   moves the whole gate assembly to the opening described in building_meta.json.
 *
 *   node tools/build_factory_shell.mjs [config.json] [out.obj]
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cfgPath = process.argv[2] || path.join(root, 'building.config.json');
const outPath = process.argv[3] || path.join(root, 'factory_precision.obj');
const legacyPath = path.join(root, 'legacy', 'factory_precision_24x16.obj');
const cfg = JSON.parse(fs.readFileSync(cfgPath, 'utf8'));

const mm = m => Math.round(m * 1000);
const LX = mm(cfg.lengthM), WY = mm(cfg.widthM), EAVE = mm(cfg.eaveM), BAY = mm(cfg.bayM), SLOPE = cfg.roofSlope;
const nBays = Math.max(1, Math.round(LX / BAY));
const frameX = Array.from({ length: nBays + 1 }, (_, i) => Math.round(i * LX / nBays));
const postLines = (cfg.postLinesM || []).map(mm).filter(y => y > 0 && y < WY);
const roofZ = y => EAVE + SLOPE * Math.min(Math.max(y, 0), Math.max(WY - y, 0));
const RIDGE = roofZ(WY / 2);
const COL = cfg.columnMm || 250, POST = cfg.postMm || 150, WALL_T = 150, LINER_T = 80;
const WAINSCOT = mm(cfg.wainscotM || 2.4);
// legacy gate: opening X 12600..16400 (centre 14500), top 4200, on the wall at Y = 16000
const LEGACY_DOOR = { cx: 14500, half: 1900, top: 4200, wallY: 16000 };
const doorCx = mm(cfg.door && cfg.door.centerXM !== undefined ? cfg.door.centerXM : cfg.lengthM / 2);
const door = { x0: doorCx - LEGACY_DOOR.half, x1: doorCx + LEGACY_DOOR.half, top: LEGACY_DOOR.top, cx: doorCx };

// ------------------------------------------------------------------ OBJ writer (flat-shaded solids)
const out = ['# Sugar Hill factory shell — generated by tools/build_factory_shell.mjs from ' + path.basename(cfgPath),
  `# ${cfg.lengthM} x ${cfg.widthM} m, eave ${cfg.eaveM} m, ${nBays} bays of ${(LX / nBays / 1000).toFixed(2)} m. Millimetres, Z-up.`];
let vCount = 0, nCount = 0, parts = 0;
const names = new Set();
function solid(name, faces) {
  if (names.has(name)) throw new Error('duplicate part name ' + name);
  names.add(name); parts++;
  out.push('o ' + name);
  for (const f of faces) {
    const [a, b, c] = f;
    const ux = b[0] - a[0], uy = b[1] - a[1], uz = b[2] - a[2], vx = c[0] - a[0], vy = c[1] - a[1], vz = c[2] - a[2];
    let nx = uy * vz - uz * vy, ny = uz * vx - ux * vz, nz = ux * vy - uy * vx;
    const l = Math.hypot(nx, ny, nz) || 1; nx /= l; ny /= l; nz /= l;
    for (const p of f) out.push(`v ${p[0].toFixed(1)} ${p[1].toFixed(1)} ${p[2].toFixed(1)}`);
    out.push(`vn ${nx.toFixed(4)} ${ny.toFixed(4)} ${nz.toFixed(4)}`);
    nCount++;
    out.push('f ' + f.map((_, i) => `${vCount + i + 1}//${nCount}`).join(' '));
    vCount += f.length;
  }
}
/** Hexahedron from 4 bottom points (counter-clockwise seen from above) and 4 top points above them. */
function hexa(name, b, t) {
  solid(name, [[b[3], b[2], b[1], b[0]], [t[0], t[1], t[2], t[3]],
    [b[0], b[1], t[1], t[0]], [b[1], b[2], t[2], t[1]], [b[2], b[3], t[3], t[2]], [b[3], b[0], t[0], t[3]]]);
}
function box(name, x0, y0, z0, x1, y1, z1) {
  hexa(name, [[x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0]], [[x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1]]);
}
/** Member running in Y from y0 to y1 whose top follows zTop0 → zTop1 (rafters, roof slabs). */
function slopedY(name, x0, x1, y0, y1, zTop0, zTop1, depth) {
  hexa(name, [[x0, y0, zTop0 - depth], [x1, y0, zTop0 - depth], [x1, y1, zTop1 - depth], [x0, y1, zTop1 - depth]],
    [[x0, y0, zTop0], [x1, y0, zTop0], [x1, y1, zTop1], [x0, y1, zTop1]]);
}

// ------------------------------------------------------------------ floor
box('Floor_Slab', 0, 0, -200, LX, WY, 0);
frameX.slice(1, -1).forEach(x => box(`Joint_X_${x}`, x - 4, 0, 0, x + 4, WY, 2));
postLines.forEach(y => box(`Joint_Y_${y}`, 0, y - 4, 0, LX, y + 4, 2));

// ------------------------------------------------------------------ steel frames
const RAFTER_D = 450, PURLIN_D = 200, RAFTER_W = 200;
let colNo = 0;
function hColumn(x, yc, top) {
  colNo++;
  const h = COL / 2, tf = 14, tw = 10, xc = Math.min(Math.max(x, h), LX - h);
  box(`Col_HBeam_${colNo}_BasePlate`, xc - h - 60, yc - h - 60, 0, xc + h + 60, yc + h + 60, 20);
  box(`Col_HBeam_${colNo}_Flange1`, xc - h, yc - h, 20, xc + h, yc - h + tf, top);
  box(`Col_HBeam_${colNo}_Flange2`, xc - h, yc + h - tf, 20, xc + h, yc + h, top);
  box(`Col_HBeam_${colNo}_Web`, xc - tw / 2, yc - h + tf, 20, xc + tw / 2, yc + h - tf, top);
}
let postNo = 0;
frameX.forEach((x, i) => {
  const end = i === 0 || i === frameX.length - 1;
  hColumn(x, COL / 2, EAVE - PURLIN_D);                     // south side wall
  hColumn(x, WY - COL / 2, EAVE - PURLIN_D);                // north side wall
  const xr0 = Math.min(Math.max(x - RAFTER_W / 2, 0), LX - RAFTER_W);
  slopedY(`Roof_Gable_Rafter_X${x}_S`, xr0, xr0 + RAFTER_W, 0, WY / 2, EAVE - PURLIN_D, RIDGE - PURLIN_D, RAFTER_D);
  slopedY(`Roof_Gable_Rafter_X${x}_N`, xr0, xr0 + RAFTER_W, WY / 2, WY, RIDGE - PURLIN_D, EAVE - PURLIN_D, RAFTER_D);
  if (!end) postLines.forEach(y => {                         // interior posts under every frame
    postNo++;
    box(`Col_Interior_Slender_${postNo}_Base`, x - 140, y - 140, 0, x + 140, y + 140, 18);
    box(`Col_Interior_Slender_${postNo}`, x - POST / 2, y - POST / 2, 18, x + POST / 2, y + POST / 2, roofZ(y) - PURLIN_D - RAFTER_D);
  });
});
// end-wall columns at the bay module across the width (both gable ends)
const endCols = Math.max(1, Math.round(WY / BAY));
for (let k = 1; k < endCols; k++) {
  const y = Math.round(k * WY / endCols), top = roofZ(y) - PURLIN_D - 20;
  box(`Col_EndWall_West_${k}`, 0, y - 100, 0, 200, y + 100, top);
  box(`Col_EndWall_East_${k}`, LX - 200, y - 100, 0, LX, y + 100, top);
}
// purlins every ~1.5 m across the slope, running the full length
const nPurlin = Math.max(2, Math.round(WY / 1524));
for (let k = 0; k <= nPurlin; k++) {
  const y = Math.round(k * WY / nPurlin), yc = Math.min(Math.max(y, 50), WY - 50), z = roofZ(y);
  box(`Roof_Purlin_Y${y}`, 0, yc - 50, z - PURLIN_D, LX, yc + 50, z);
}
// girts on the inside face of all four walls (the north ones stop at the door opening)
(cfg.girtsM || []).map(mm).forEach((z, gi) => {
  const tag = gi === 0 ? 'Low' : gi === 1 ? 'High' : 'L' + (gi + 1);
  box(`Girt_South_${tag}`, 0, 20, z, LX, 120, z + 90);
  if (z < door.top) { box(`Girt_North_${tag}_W`, 0, WY - 120, z, door.x0, WY - 20, z + 90); box(`Girt_North_${tag}_E`, door.x1, WY - 120, z, LX, WY - 20, z + 90); }
  else box(`Girt_North_${tag}`, 0, WY - 120, z, LX, WY - 20, z + 90);
  box(`Girt_West_${tag}`, 20, 0, z, 120, WY, z + 90);
  box(`Girt_East_${tag}`, LX - 120, 0, z, LX - 20, WY, z + 90);
});

// ------------------------------------------------------------------ skin
box('Wall_South_Full', 0, -WALL_T, 0, LX, 0, EAVE);
box('Wall_North_WestSeg', 0, WY, 0, door.x0, WY + WALL_T, EAVE);
box('Wall_North_EastSeg', door.x1, WY, 0, LX, WY + WALL_T, EAVE);
box('Wall_North_TopDoor1', door.x0, WY, door.top, door.x1, WY + WALL_T, EAVE);
box('Wall_West', -WALL_T, 0, 0, 0, WY, EAVE);
box('Wall_East', LX, 0, 0, LX + WALL_T, WY, EAVE);
function gablePeak(name, x0, x1) {                           // triangular prism above the eave line
  const a = [x0, 0, EAVE], b = [x0, WY, EAVE], c = [x0, WY / 2, RIDGE], d = [x1, 0, EAVE], e = [x1, WY, EAVE], f = [x1, WY / 2, RIDGE];
  solid(name, [[a, c, b], [d, e, f], [a, b, e, d], [b, c, f, e], [c, a, d, f]]);
}
gablePeak('Wall_West_Gable_Peak', -WALL_T, 0);
gablePeak('Wall_East_Gable_Peak', LX, LX + WALL_T);
box('LinerPanel_South', 0, 10, 0, LX, 10 + LINER_T, WAINSCOT);
box('LinerPanel_North_WestSeg', 0, WY - 10 - LINER_T, 0, door.x0, WY - 10, WAINSCOT);
box('LinerPanel_North_EastSeg', door.x1, WY - 10 - LINER_T, 0, LX, WY - 10, WAINSCOT);
box('LinerPanel_West', 10, 0, 0, 10 + LINER_T, WY, WAINSCOT);
box('LinerPanel_East', LX - 10 - LINER_T, 0, 0, LX - 10, WY, WAINSCOT);
slopedY('Roof_Gable_Cladding_South', -200, LX + 200, -300, WY / 2, EAVE + 60 - 300 * SLOPE, RIDGE + 60, 60);
slopedY('Roof_Gable_Cladding_North', -200, LX + 200, WY / 2, WY + 300, RIDGE + 60, EAVE + 60 - 300 * SLOPE, 60);

// ------------------------------------------------------------------ ceiling lights: one per bay in each row
const L = cfg.lights || {}, rows = Math.max(1, L.rows || 3), ls = (L.sizeMm || 500) / 2, drop = L.dropMm === undefined ? 700 : L.dropMm;
for (let r = 0; r < rows; r++) {
  const y = Math.round((r + 0.5) * WY / rows), z = roofZ(y) - PURLIN_D - drop;
  for (let i = 0; i < nBays; i++) {
    const x = Math.round((frameX[i] + frameX[i + 1]) / 2);
    box(`HighBay_LED_Row${r + 1}_X${x}`, x - ls, y - ls, z, x + ls, y + ls, z + 120);
  }
}

// ------------------------------------------------------------------ yellow floor lines
const FL = cfg.floorLines || {}, inset = mm(FL.insetM === undefined ? 2.5 : FL.insetM), lw = 50;
box('SafetyLine_Border_South', inset, inset - lw, 0, LX - inset, inset + lw, 4);
box('SafetyLine_Border_North', inset, WY - inset - lw, 0, LX - inset, WY - inset + lw, 4);
box('SafetyLine_Border_West', inset - lw, inset, 0, inset + lw, WY - inset, 4);
box('SafetyLine_Border_East', LX - inset - lw, inset, 0, LX - inset + lw, WY - inset, 4);
const off = mm(FL.aisleOffsetM === undefined ? 1.5 : FL.aisleOffsetM);
postLines.forEach((y, i) => {                                // aisle edges beside each post line, on the side facing the middle
  const ya = y + (y < WY / 2 ? off : -off);
  box(`SafetyLine_Aisle_${i + 1}`, inset, ya - lw, 0, LX - inset, ya + lw, 4);
});

// ------------------------------------------------------------------ the animated gate, copied from the original model
let gateParts = 0;
if (fs.existsSync(legacyPath)) {
  const V = [], N = []; let cur = null; const objs = [];
  for (const line of fs.readFileSync(legacyPath, 'utf8').split(/\r?\n/)) {
    if (line.startsWith('v ')) V.push(line.slice(2).trim());
    else if (line.startsWith('vn ')) N.push(line.slice(3).trim());
    else if (line.startsWith('o ') || line.startsWith('g ')) { cur = { name: line.slice(2).trim(), faces: [] }; objs.push(cur); }
    else if (line.startsWith('f ') && cur) cur.faces.push(line.slice(2).trim().split(/\s+/));
  }
  for (const o of objs) {
    if (!o.name.startsWith('Door_Sectional_') || !o.faces.length) continue;
    names.add(o.name); parts++; gateParts++;
    out.push('o ' + o.name);
    const vMap = new Map(), nMap = new Map();
    const lines = [];
    for (const f of o.faces) {
      lines.push('f ' + f.map(tok => {
        const [vi, , ni] = tok.split('/');
        if (!vMap.has(vi)) { vMap.set(vi, ++vCount); out.push('v ' + V[parseInt(vi, 10) - 1]); }
        if (ni && !nMap.has(ni)) { nMap.set(ni, ++nCount); out.push('vn ' + N[parseInt(ni, 10) - 1]); }
        return ni ? `${vMap.get(vi)}//${nMap.get(ni)}` : `${vMap.get(vi)}`;
      }).join(' '));
    }
    out.push(...lines);
  }
} else console.warn('! legacy model not found, building has an opening but no gate parts:', legacyPath);

fs.writeFileSync(outPath, out.join('\n') + '\n');
const meta = {
  generatedFrom: path.basename(cfgPath), units: 'mm', lengthX: LX, widthY: WY, eave: EAVE, ridge: Math.round(RIDGE), bays: nBays, bay: Math.round(LX / nBays),
  postLinesY: postLines, wainscot: WAINSCOT,
  door: { wall: 'NORTH', centerX: door.cx, x0: door.x0, x1: door.x1, top: door.top, legacyCenterX: LEGACY_DOOR.cx, legacyWallY: LEGACY_DOOR.wallY }
};
fs.writeFileSync(path.join(path.dirname(outPath), 'building_meta.json'), JSON.stringify(meta, null, 2) + '\n');
console.log(`wrote ${path.relative(root, outPath)}: ${parts} parts (${gateParts} gate parts copied), ${(LX / 1000).toFixed(2)} x ${(WY / 1000).toFixed(2)} m, eave ${(EAVE / 1000).toFixed(2)} m, ridge ${(RIDGE / 1000).toFixed(2)} m, ${nBays} bays, ${postLines.length} post line(s)`);
